#!/usr/bin/env node
// AUTO-GENERATION DRIVER — invoked by `make types` (root Makefile) or
// `npm run generate:types`. Do not hand-edit the files it writes.
//
// Source of truth: the Pydantic models in `packages/contracts` are the
// single source of truth for the PROTÉGÉ domain vocabulary (roadmap P1).
// `python -m protege.contracts.export content/schema` renders them to
// deterministic JSON Schema; this script renders that JSON Schema to
// TypeScript. Nothing under `src/generated/` is ever edited by hand — the
// CI drift check (`.github/workflows/ci.yml`, job `types`) re-runs both
// steps and fails the build if the committed output does not match.

import { compileFromFile } from "json-schema-to-typescript";
import { mkdir, readFile, writeFile, rm } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = path.resolve(__dirname, "..", "..", "..");
const SCHEMA_DIR = path.join(REPO_ROOT, "content", "schema");
const OUT_DIR = path.join(__dirname, "..", "src", "generated", "contracts");

const BANNER =
  "/* eslint-disable */\n" +
  "/**\n" +
  " * AUTO-GENERATED by `apps/web/scripts/generate-contract-types.mjs` from\n" +
  " * `content/schema/{name}.json`, which is itself generated from the\n" +
  " * Pydantic models in `packages/contracts` (roadmap P1). Do not edit by\n" +
  " * hand — run `make types` (repo root) to regenerate.\n" +
  " */";

const COMPILE_OPTIONS = {
  bannerComment: "",
  style: {
    semi: true,
    singleQuote: false,
    printWidth: 100,
    trailingComma: "all",
  },
  $refOptions: { dereference: { circular: false } },
};

async function main() {
  const index = JSON.parse(await readFile(path.join(SCHEMA_DIR, "index.json"), "utf-8"));
  const models = index.models;
  if (!Array.isArray(models) || models.length === 0) {
    throw new Error(`content/schema/index.json has no "models" list`);
  }

  await rm(OUT_DIR, { recursive: true, force: true });
  await mkdir(OUT_DIR, { recursive: true });

  const barrelLines = [
    BANNER,
    "",
    "// Re-exported under a per-model namespace so identically-named nested",
    "// types (e.g. `Distractor`, embedded in both `LearningItem` and",
    "// `ItemVersion`) never collide across models in this barrel.",
    "",
  ];

  for (const model of models) {
    const schemaPath = path.join(SCHEMA_DIR, `${model}.json`);
    const ts = await compileFromFile(schemaPath, COMPILE_OPTIONS);
    await writeFile(path.join(OUT_DIR, `${model}.ts`), `${BANNER}\n\n${ts}`, "utf-8");
    barrelLines.push(`export * as ${model}Schema from "./${model}";`);
  }

  await writeFile(path.join(OUT_DIR, "index.ts"), barrelLines.join("\n") + "\n", "utf-8");

  console.log(`Generated ${models.length} contract type file(s) + index.ts -> ${OUT_DIR}`);
}

main().catch((err) => {
  console.error(err);
  process.exitCode = 1;
});
